import { relations, sql } from "drizzle-orm";
import {
	boolean,
	customType,
	doublePrecision,
	index,
	integer,
	pgEnum,
	pgTable,
	primaryKey,
	text,
	timestamp,
} from "drizzle-orm/pg-core";
import { user } from "./auth";
import { languages, regions } from "./profile";

/**
 * Content and its lifecycle (spec §4.3, §5).
 *
 * Status is the spine of the whole module: a piece of content is only visible
 * to end users while `published` and not held, and every move between states
 * goes through one `transition()` function rather than ad-hoc updates.
 */
export const contentStatusEnum = pgEnum("content_status", [
	"draft",
	"pending_review",
	"published",
	"rejected",
	"removed",
]);

export const CONTENT_STATUSES = contentStatusEnum.enumValues;
export type ContentStatus = (typeof CONTENT_STATUSES)[number];

export const tagCategoryEnum = pgEnum("tag_category", [
	"festival",
	"language",
	"region",
	"theme",
	"occasion",
]);

export const TAG_CATEGORIES = tagCategoryEnum.enumValues;
export type TagCategory = (typeof TAG_CATEGORIES)[number];

/**
 * Postgres `tsvector`, which Drizzle has no first-class column type for.
 * Populated by the database as a generated column, never written by hand.
 */
const tsvector = customType<{ data: string }>({
	dataType() {
		return "tsvector";
	},
});

/** What the feed considers visible. Every feed index is partial on this. */
const sqlPublished = sql`status = 'published' AND visibility_hold = false`;

export const content = pgTable(
	"content",
	{
		id: text("id").primaryKey(),
		designerId: text("designer_id")
			.notNull()
			.references(() => user.id, { onDelete: "cascade" }),
		title: text("title").notNull(),
		description: text("description"),
		status: contentStatusEnum("status").default("draft").notNull(),
		primaryLanguage: text("primary_language")
			.notNull()
			.references(() => languages.code),
		// Null means global: eligible for every user's feed regardless of region.
		// This is what stops a user in an underserved region seeing an empty feed.
		regionCode: text("region_code").references(() => regions.code),

		// Denormalised running total. The authoritative history is
		// download_events; this exists so listings do not aggregate on every read.
		downloadCount: integer("download_count").default(0).notNull(),

		// --- Materialised feed ranking (spec §7) ---
		//
		// The feed used to compute these per row, per request: a lateral count
		// over download_events for every published item, then a sort over all of
		// them. Measured at 200k items that was 4.7 seconds a page. Precomputing
		// the parts of the score that do not depend on who is asking turns the
		// query into six bounded index scans.

		/** Downloads in the popularity window, refreshed nightly. */
		recentDownloads: integer("recent_downloads").default(0).notNull(),

		/**
		 * Recency decay plus popularity — everything in the score that is the
		 * same for every viewer. The viewer's language and region are added at
		 * query time as one of six constants, which is what lets each partition
		 * be read straight off an index in score order.
		 */
		baseScore: doublePrecision("base_score").default(0).notNull(),

		/**
		 * The image the feed shows, denormalised from `content_assets`.
		 *
		 * A feed tile needs one image, and fetching it per row was the second of
		 * the two lateral joins. Written when the first asset is confirmed.
		 */
		primaryAssetKey: text("primary_asset_key"),

		// Set automatically once reports pass the threshold, dropping the item
		// out of the feed until an admin rules on it.
		visibilityHold: boolean("visibility_hold").default(false).notNull(),

		submittedAt: timestamp("submitted_at"),
		reviewedAt: timestamp("reviewed_at"),
		reviewedBy: text("reviewed_by").references(() => user.id, {
			onDelete: "set null",
		}),
		rejectionReason: text("rejection_reason"),
		publishedAt: timestamp("published_at"),
		removedAt: timestamp("removed_at"),

		createdAt: timestamp("created_at").defaultNow().notNull(),
		updatedAt: timestamp("updated_at")
			.defaultNow()
			.$onUpdate(() => new Date())
			.notNull(),

		// Generated by Postgres so it can never drift from the title.
		// `simple` rather than `english`: titles are largely Hindi, Marathi,
		// Tamil and so on, where English stemming would do harm rather than good.
		titleTsv: tsvector("title_tsv").generatedAlwaysAs(
			sql`to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(description, ''))`,
		),
	},
	(table) => [
		// --- The feed's three access paths (spec §7) ---
		//
		// All partial on published-and-unheld, which is both what the feed asks
		// for and a small fraction of the table, so the indexes stay narrow and
		// a draft or a removed item costs nothing to carry.

		// Each is (something to seek on, then score) so a group can be read in
		// ranking order and stopped at a page, rather than read whole and sorted.
		// The `.desc()` matters: it emits DESC NULLS LAST, and a query ordering by
		// plain DESC — which Postgres reads as NULLS FIRST — cannot use them.

		// Score alone, for the groups defined by *not* matching the viewer's
		// language, which have no value to seek on.
		index("content_feed_score_idx")
			.on(table.baseScore.desc(), table.id.desc())
			.where(sqlPublished),
		// Language then score, for the groups that do match.
		index("content_feed_lang_idx")
			.on(table.primaryLanguage, table.baseScore.desc(), table.id.desc())
			.where(sqlPublished),
		// Region then score, for the viewer's own region.
		index("content_feed_region_idx")
			.on(table.regionCode, table.baseScore.desc(), table.id.desc())
			.where(sqlPublished),
		// Recency, for search with no term and for the nightly refresh.
		index("content_published_at_idx")
			.on(table.publishedAt.desc())
			.where(sqlPublished),
		index("content_designer_idx").on(table.designerId, table.createdAt),
		// The admin review queue, oldest first so nothing is starved.
		index("content_review_queue_idx").on(table.status, table.submittedAt),
		// The nightly orphan sweep looks for drafts untouched for a week. Partial
		// so it stays tiny: drafts are a small and short-lived minority of rows.
		index("content_stale_draft_idx")
			.on(table.updatedAt)
			.where(sql`status = 'draft'`),
		// The admin browse and audit lookup, newest first across every status.
		index("content_created_at_idx").on(table.createdAt),
		index("content_language_idx").on(table.primaryLanguage),
		index("content_region_idx").on(table.regionCode),
		index("content_title_tsv_idx").using("gin", table.titleTsv),
		// Trigram index for misspelled searches, which older users make often.
		index("content_title_trgm_idx").using(
			"gin",
			sql`${table.title} gin_trgm_ops`,
		),
	],
);

export const contentAssets = pgTable(
	"content_assets",
	{
		id: text("id").primaryKey(),
		contentId: text("content_id")
			.notNull()
			.references(() => content.id, { onDelete: "cascade" }),
		// Object key in R2. Unique so a client cannot confirm one upload twice
		// and attach it to two pieces of content.
		storageKey: text("storage_key").notNull().unique(),
		mimeType: text("mime_type").notNull(),
		width: integer("width").notNull(),
		height: integer("height").notNull(),
		bytes: integer("bytes").notNull(),
		checksum: text("checksum"),
		createdAt: timestamp("created_at").defaultNow().notNull(),
	},
	(table) => [index("content_assets_content_idx").on(table.contentId)],
);

export const tags = pgTable(
	"tags",
	{
		id: text("id").primaryKey(),
		slug: text("slug").notNull().unique(),
		label: text("label").notNull(),
		category: tagCategoryEnum("category").notNull(),
		isActive: boolean("is_active").default(true).notNull(),
		createdAt: timestamp("created_at").defaultNow().notNull(),
	},
	(table) => [index("tags_category_idx").on(table.category, table.isActive)],
);

export const contentTags = pgTable(
	"content_tags",
	{
		contentId: text("content_id")
			.notNull()
			.references(() => content.id, { onDelete: "cascade" }),
		tagId: text("tag_id")
			.notNull()
			.references(() => tags.id, { onDelete: "cascade" }),
	},
	(table) => [
		primaryKey({ columns: [table.contentId, table.tagId] }),
		// Drives tag filtering in search: given a tag, find its content.
		index("content_tags_tag_idx").on(table.tagId),
	],
);

export const contentRelations = relations(content, ({ one, many }) => ({
	designer: one(user, {
		fields: [content.designerId],
		references: [user.id],
	}),
	language: one(languages, {
		fields: [content.primaryLanguage],
		references: [languages.code],
	}),
	region: one(regions, {
		fields: [content.regionCode],
		references: [regions.code],
	}),
	assets: many(contentAssets),
	contentTags: many(contentTags),
}));

export const contentAssetRelations = relations(contentAssets, ({ one }) => ({
	content: one(content, {
		fields: [contentAssets.contentId],
		references: [content.id],
	}),
}));

export const tagRelations = relations(tags, ({ many }) => ({
	contentTags: many(contentTags),
}));

export const contentTagRelations = relations(contentTags, ({ one }) => ({
	content: one(content, {
		fields: [contentTags.contentId],
		references: [content.id],
	}),
	tag: one(tags, { fields: [contentTags.tagId], references: [tags.id] }),
}));
